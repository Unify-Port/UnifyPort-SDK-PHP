<?php

declare(strict_types=1);

namespace UnifyPort\Sdk\Tests\Support;

use Psr\Http\Message\StreamInterface;

final class TrackingStream implements StreamInterface
{
    public bool $closed = false;

    public function __construct(private readonly StreamInterface $inner)
    {
    }

    public function __toString(): string
    {
        return (string) $this->inner;
    }

    public function close(): void
    {
        // 测试显式记录 close，验证异常响应不会占用 transport 连接资源。
        $this->closed = true;
        $this->inner->close();
    }

    public function detach()
    {
        return $this->inner->detach();
    }

    public function getSize(): ?int
    {
        return $this->inner->getSize();
    }

    public function tell(): int
    {
        return $this->inner->tell();
    }

    public function eof(): bool
    {
        return $this->inner->eof();
    }

    public function isSeekable(): bool
    {
        return $this->inner->isSeekable();
    }

    public function seek(int $offset, int $whence = SEEK_SET): void
    {
        $this->inner->seek($offset, $whence);
    }

    public function rewind(): void
    {
        $this->inner->rewind();
    }

    public function isWritable(): bool
    {
        return $this->inner->isWritable();
    }

    public function write(string $string): int
    {
        return $this->inner->write($string);
    }

    public function isReadable(): bool
    {
        return $this->inner->isReadable();
    }

    public function read(int $length): string
    {
        return $this->inner->read($length);
    }

    public function getContents(): string
    {
        return $this->inner->getContents();
    }

    public function getMetadata(?string $key = null)
    {
        return $this->inner->getMetadata($key);
    }
}
